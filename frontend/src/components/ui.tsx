import type { UseQueryResult } from '@tanstack/react-query';
import { AlertOctagon, AlertTriangle, CheckCircle2, CircleSlash, Globe, Link2Off, Radio, ShieldQuestion } from 'lucide-react';
import type { ButtonHTMLAttributes, ReactNode } from 'react';
import { ApiError } from '../lib/api';
import { title as titleCase } from '../lib/format';
import type { DataSource } from '../lib/types';

const SOURCE: Record<DataSource, { label: string; hint: string }> = {
  SIMULATED: { label: 'Simulated data', hint: 'Generated by the CloudPulse simulator, not read from a real cloud account.' },
  SIMULATED_LIVE: { label: 'Simulated live data', hint: 'Generated readings refreshed every 15 seconds, not read from a real cloud account.' },
  AWS: { label: 'AWS data', hint: 'Read from a connected AWS account.' },
  AZURE: { label: 'Azure data', hint: 'Read from a connected Azure subscription.' },
  LIVE_KUBERNETES: { label: 'Live Kubernetes', hint: 'Read from a connected Kubernetes cluster.' },
};

export function DataBadge({ source }: { source: DataSource | undefined }) {
  if (!source) return null;
  const { label, hint } = SOURCE[source];
  const simulated = source.startsWith('SIMULATED');
  return (
    <span title={hint} className={`inline-flex shrink-0 items-center gap-1.5 rounded-full border border-line px-2.5 py-0.5 text-xs font-medium ${simulated ? 'text-muted' : 'text-ok'}`}>
      <Radio size={12} aria-hidden /> {label}
    </span>
  );
}

const STATUS: Record<string, { label: string; className: string; Icon: typeof CheckCircle2 }> = {
  healthy: { label: 'Healthy', className: 'text-ok', Icon: CheckCircle2 },
  warning: { label: 'Warning', className: 'text-warn', Icon: AlertTriangle },
  critical: { label: 'Critical', className: 'text-crit', Icon: AlertOctagon },
  degraded: { label: 'Degraded', className: 'text-warn', Icon: AlertTriangle },
  no_telemetry: { label: 'No telemetry', className: 'text-muted', Icon: CircleSlash },
  orphaned: { label: 'Orphaned', className: 'text-warn', Icon: Link2Off },
  external: { label: 'External', className: 'text-muted', Icon: Globe },
  active: { label: 'Active', className: 'text-ok', Icon: CheckCircle2 },
  not_configured: { label: 'Not configured', className: 'text-muted', Icon: CircleSlash },
  simulated: { label: 'Simulated', className: 'text-muted', Icon: Radio },
};

export function statusMeta(status: string) {
  return STATUS[status] ?? { label: titleCase(status), className: 'text-muted', Icon: ShieldQuestion };
}

export function Status({ status }: { status: string }) {
  const { label, className, Icon } = statusMeta(status);
  return (
    <span className={`inline-flex items-center gap-1.5 whitespace-nowrap text-sm font-medium ${className}`}>
      <Icon size={15} aria-hidden /> {label}
    </span>
  );
}

export function PageHeader({ heading, intro, source, children }: { heading: string; intro?: ReactNode; source?: DataSource; children?: ReactNode }) {
  return (
    <header className="mb-6 flex flex-wrap items-start justify-between gap-x-6 gap-y-3">
      <div className="max-w-2xl">
        <h1 className="font-display text-3xl font-semibold tracking-tight">{heading}</h1>
        {intro && <p className="mt-1 text-muted">{intro}</p>}
      </div>
      <div className="flex flex-wrap items-center gap-3">
        <DataBadge source={source} />
        {children}
      </div>
    </header>
  );
}

export function Panel({ heading, note, action, children, className = '' }: { heading?: string; note?: ReactNode; action?: ReactNode; children: ReactNode; className?: string }) {
  return (
    <section className={`min-w-0 rounded-lg bg-panel p-4 sm:p-5 ${className}`}>
      {(heading || action) && (
        <div className="mb-3 flex flex-wrap items-start justify-between gap-x-4 gap-y-2">
          <div className="min-w-0">
            {heading && <h2 className="font-display text-lg font-semibold">{heading}</h2>}
            {note && <p className="text-sm text-muted">{note}</p>}
          </div>
          {action}
        </div>
      )}
      {children}
    </section>
  );
}

/** A row of plain figures, separated by space rather than boxes. */
export function Figures({ items }: { items: { label: string; value: ReactNode; detail?: ReactNode }[] }) {
  return (
    <dl className="grid grid-cols-2 gap-x-6 gap-y-4 lg:grid-flow-col lg:auto-cols-fr lg:grid-cols-none">
      {items.map((item) => (
        <div key={item.label} className="min-w-0">
          <dt className="text-sm text-muted">{item.label}</dt>
          <dd className="num font-display text-2xl font-semibold">{item.value}</dd>
          {item.detail && <dd className="text-sm text-muted">{item.detail}</dd>}
        </div>
      ))}
    </dl>
  );
}

export function Loading({ label = 'Loading' }: { label?: string }) {
  return (
    <div role="status" className="flex items-center gap-3 py-10 text-muted">
      <span className="beat size-2 rounded-full bg-accent" aria-hidden />
      {label}
    </div>
  );
}

export function ErrorNote({ error, onRetry }: { error: unknown; onRetry?: () => void }) {
  const message = error instanceof Error ? error.message : 'The request failed.';
  const denied = error instanceof ApiError && error.status === 403;
  return (
    <div role="alert" className="rounded-lg bg-panel p-5">
      <p className="font-medium text-crit">{denied ? 'Your role does not include this.' : 'This data could not be loaded.'}</p>
      <p className="mt-1 text-muted">{message}</p>
      {onRetry && !denied && <Button className="mt-3" onClick={onRetry}>Try again</Button>}
    </div>
  );
}

export function Query<T>({ q, children }: { q: UseQueryResult<T>; children: (data: T) => ReactNode }) {
  if (q.isPending) return <Loading />;
  if (q.isError) return <ErrorNote error={q.error} onRetry={() => q.refetch()} />;
  return <>{children(q.data)}</>;
}

export function Empty({ children }: { children: ReactNode }) {
  return <p className="py-6 text-muted">{children}</p>;
}

export function Button({ variant = 'secondary', className = '', ...props }: ButtonHTMLAttributes<HTMLButtonElement> & { variant?: 'primary' | 'secondary' | 'danger' }) {
  const look = {
    primary: 'bg-accent text-on-accent hover:opacity-90',
    secondary: 'bg-raised text-ink hover:bg-line',
    danger: 'bg-crit text-panel hover:opacity-90',
  }[variant];
  return <button type="button" {...props} className={`inline-flex min-h-9 cursor-pointer items-center justify-center gap-2 rounded-md px-3.5 py-1.5 text-sm font-medium disabled:cursor-not-allowed disabled:opacity-50 ${look} ${className}`} />;
}

export function Select({ label, value, onChange, options }: { label: string; value: string; onChange: (value: string) => void; options: { value: string; label: string }[] }) {
  return (
    <label className="flex min-w-0 items-center gap-2 text-sm text-muted">
      {label}
      <select value={value} onChange={(e) => onChange(e.target.value)} className="min-h-9 min-w-0 max-w-44 rounded-md border border-line bg-panel px-2 py-1 text-sm text-ink">
        {options.map((option) => <option key={option.value} value={option.value}>{option.label}</option>)}
      </select>
    </label>
  );
}

export function Segmented<T extends string | number>({ label, value, onChange, options }: { label: string; value: T; onChange: (value: T) => void; options: { value: T; label: string }[] }) {
  return (
    <div role="group" aria-label={label} className="inline-flex rounded-md bg-raised p-0.5">
      {options.map((option) => (
        <button
          key={option.value}
          type="button"
          aria-pressed={option.value === value}
          onClick={() => onChange(option.value)}
          className={`min-h-8 cursor-pointer rounded px-2.5 text-sm font-medium ${option.value === value ? 'bg-panel text-ink' : 'text-muted hover:text-ink'}`}
        >
          {option.label}
        </button>
      ))}
    </div>
  );
}

export function Meter({ value, warn, crit, label }: { value: number | null | undefined; warn: number; crit: number; label: string }) {
  if (value === null || value === undefined) return <span className="text-muted">n/a</span>;
  const tone = value >= crit ? 'bg-crit-mark' : value >= warn ? 'bg-warn-mark' : 'bg-accent';
  return (
    <div className="flex items-center gap-2" role="img" aria-label={`${label} ${value.toFixed(1)}%`}>
      <span className="num w-11 shrink-0 text-right text-sm">{value.toFixed(0)}%</span>
      <span className="h-1.5 w-full min-w-10 overflow-hidden rounded-full bg-raised">
        <span className={`block h-full rounded-full ${tone}`} style={{ width: `${Math.min(100, Math.max(0, value))}%` }} />
      </span>
    </div>
  );
}

